// Generates lib/world-map.ts (SVG paths) from Natural Earth data. Run: node scripts/build-map.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { feature } from "topojson-client";
import { geoNaturalEarth1, geoPath } from "d3-geo";

const topo = JSON.parse(readFileSync("node_modules/world-atlas/countries-110m.json", "utf8"));
const all = feature(topo, topo.objects.countries).features.filter((f) => f.id !== "010"); // drop Antarctica

const W = 1000, H = 500;
const projection = geoNaturalEarth1().fitExtent([[6, 6], [W - 6, H - 6]], { type: "FeatureCollection", features: all });
const path = geoPath(projection).digits(0);

const highlight = { "840": "US", "826": "UK", "616": "PL", "804": "UA", "398": "KZ" };
const pinsLonLat = { US: [-98, 39], UK: [-2, 53.5], PL: [19.5, 52], UA: [31, 49], KZ: [67, 48] };

const land = all.filter((f) => !highlight[f.id]).map((f) => path(f)).filter(Boolean).join("");
const countries = all.filter((f) => highlight[f.id]).map((f) => ({ code: highlight[f.id], d: path(f) }));
const pins = Object.fromEntries(Object.entries(pinsLonLat).map(([k, ll]) => [k, projection(ll).map((n) => Math.round(n * 10) / 10)]));

const out = `// Generated by scripts/build-map.mjs from world-atlas (Natural Earth, public domain). Do not edit.
export const worldMap = ${JSON.stringify({ viewBox: "0 30 1000 420", land, countries, pins })} as const;
`;
writeFileSync("lib/world-map.ts", out);
console.log("ok", (out.length / 1024).toFixed(0) + " KB", pins);
